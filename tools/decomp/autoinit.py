"""Generate the static initialisers of files that only include <iostream>.

Every C++ file that includes <iostream> gets a `_GLOBAL__sub_I_<file>` function constructing its
`std::ios_base::Init` object and registering the destructor with __aeabi_atexit. When that is
the file's only static initialisation the function's shape is fixed, so each such function in
rbp gets a generated one-line source file (one file per function: GCC emits one initialiser per
file). Writes src/auto/ioinit/ioinit_<addr>.cpp and obj/auto_ioinit.pairs. Run from decomp/.
"""
import os
import struct
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from elfinfo import Elf

e = Elf('rbp.orig')
starts = sorted(int(l.split()[0], 16) for l in open('split/functions.txt') if l.startswith('0x'))
size = {a: b - a for a, b in zip(starts, starts[1:])}
grafted = {int(l.split()[0], 16) for l in open('grafts.txt') if l.strip() and l[0] != '#'
           and not l.split()[2].startswith('src/auto/ioinit/')}

# push {r4,lr}; movw/movt r4, init; mov r0,r4; bl ios_base::Init::Init; mov r0,r4;
# movw r1/r2 (dtor, __dso_handle), movt r1/r2; pop {r4,lr}; b __aeabi_atexit
SHAPE = [0xe92d4010, 0xe3004000, 0xe3404000, 0xe1a00004, None, 0xe1a00004,
         0xe3001000, 0xe3002000, 0xe3401000, 0xe3402000, 0xe8bd4010, None]
MASK = [0xffffffff, 0xfff0f000, 0xfff0f000, 0xffffffff, None, 0xffffffff,
        0xfff0f000, 0xfff0f000, 0xfff0f000, 0xfff0f000, 0xffffffff, None]

labels = {}
for l in open('split/labels.txt'):
    p = l.split()
    if len(p) == 2:
        labels.setdefault(int(p[0], 16), p[1])


def bl_target(w, at):
    off = w & 0xffffff
    return at + 8 + ((off - 0x1000000) if off & 0x800000 else off) * 4


os.makedirs('src/auto/ioinit', exist_ok=True)
pairs = []
for a, s in sorted(size.items()):
    if a in grafted or s != 48:
        continue
    w = struct.unpack('<12I', e.read_va(a, 48))
    if all(sh is None or (x & m) == sh for x, sh, m in zip(w, SHAPE, MASK)) and \
            w[4] & 0x0f000000 == 0x0b000000 and w[11] & 0x0f000000 == 0x0a000000 and \
            labels.get(bl_target(w[4], a + 16)) == 'p__ZNSt8ios_base4InitC1Ev':
        name = f'ioinit_{a:x}'
        open(f'src/auto/ioinit/{name}.cpp', 'w').write(
            '// Generated by autoinit.py: a file that includes <iostream> and has no other static\n'
            '// initialisation (rbp 0x%x).\n#include <iostream>\n' % a)
        pairs.append((f'_GLOBAL__sub_I_{name}.cpp', a))
open('obj/auto_ioinit.pairs', 'w').write(''.join(f'{n}={a:#x}\n' for n, a in pairs))
print(len(pairs), 'initialisers')
