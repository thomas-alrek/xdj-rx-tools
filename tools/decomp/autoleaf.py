"""Generate tiny functions outside the vtables from their bytes (names are placeholders).

Shapes (whole function, 4 or 8 bytes):
  bx lr                              -> void f() {}
  mov/mvn/movw r0, #imm ; bx lr      -> int f() { return imm; }
  ldr/ldrb/ldrh/ldrsb/ldrsh r0,[r0,#o]; bx lr -> field getter
  add r0, r0, #o ; bx lr             -> address of a member
  str/strb r1, [r0, #o] ; bx lr      -> field setter
  b target                           -> forward all four argument registers to target
  ldr r0,[r0,#o] ; b target          -> forward to a member object's method
  add r0, r0, #o ; b target          -> forward to an embedded member's method
Tail-call targets get the target's split label as assembler name. Writes src/auto/auto_leaf.cpp
and obj/auto_leaf.pairs. Run from decomp/.
"""
import os
import struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from elfinfo import Elf
e = Elf('rbp.orig')
starts = sorted(int(l.split()[0], 16) for l in open('split/functions.txt') if l.startswith('0x'))
size = {a: b - a for a, b in zip(starts, starts[1:])}
grafted = {int(l.split()[0], 16) for l in open('grafts.txt') if l.strip() and l[0] != '#' and l.split()[2] != 'src/auto/auto_leaf.cpp'}   # own earlier output is regenerated
labels = {}
for l in open('split/labels.txt'):
    p = l.split()
    if len(p) == 2:
        labels.setdefault(int(p[0], 16), p[1])

def rot_imm(w):
    imm, rot = w & 0xff, (w >> 8) & 0xf
    return ((imm >> (2 * rot)) | (imm << (32 - 2 * rot))) & 0xffffffff

def branch(w, a):
    off = w & 0xffffff
    return a + 8 + ((off - 0x1000000) if off & 0x800000 else off) * 4

BX = 0xe12fff1e
src = ['// Generated by scripts/autoleaf.py: tiny functions rebuilt from their bytes.', '',
       'struct S { char bytes[4096]; };',
       'struct VTab { ' + ' '.join(f'virtual void m{k} (int, int);' for k in range(96)) + ' };',
       '', 'extern "C" {', '']
pairs, decls = [], set()

def field(off, ty):
    return f'*({ty}*) ((char*) p + {off})'

def callee(target, extra=''):
    name = labels[target]
    fn = f'callee_{target:x}'
    if fn not in decls:
        decls.add(fn)
        src.append(f'extern void {fn} (void*, int, int, int) __asm__ ("{name}");')
    return fn

for a, s in sorted(size.items()):
    if a in grafted or a < 0xeda0 or a >= 0x2d0000 or s not in (4, 8, 12, 16, 20, 24, 28):
        continue
    w = struct.unpack(f'<{s // 4}I', e.read_va(a, s))
    n = f'leaf_{a:x}'
    body = None
    if s == 4 and w[0] == BX:
        body, sig = '{}', f'void {n} ()'
    elif s == 4 and w[0] & 0xff000000 == 0xea000000 and branch(w[0], a) in labels:
        fn = callee(branch(w[0], a))
        sig, body = f'void {n} (void* a, int b, int c, int d)', f'{{ {fn} (a, b, c, d); }}'
    elif s == 8 and w[1] == BX:
        x = w[0]
        if x & 0xfffff000 == 0xe3a00000:
            sig, body = f'int {n} ()', f'{{ return {rot_imm(x) - (1 << 32) if rot_imm(x) >= 0x80000000 else rot_imm(x)}; }}'
        elif x & 0xfffff000 == 0xe3e00000:
            v = ~rot_imm(x) & 0xffffffff
            sig, body = f'int {n} ()', f'{{ return {v - (1 << 32) if v >= 0x80000000 else v}; }}'
        elif x & 0xfff0f000 == 0xe3000000:
            v = ((x >> 4) & 0xf000) | (x & 0xfff)
            sig, body = f'int {n} ()', f'{{ return {v}; }}'
        elif x & 0xfffff000 == 0xe5900000:
            sig, body = f'int {n} (S* p)', f'{{ return {field(x & 0xfff, "int")}; }}'
        elif x & 0xfffff000 == 0xe5d00000:
            sig, body = f'unsigned char {n} (S* p)', f'{{ return {field(x & 0xfff, "unsigned char")}; }}'
        elif x & 0xfff0f0f0 in (0xe1d000b0, 0xe1d000d0, 0xe1d000f0):
            ty = {0xb0: 'unsigned short', 0xd0: 'signed char', 0xf0: 'short'}[x & 0xf0]
            off = ((x >> 4) & 0xf0) | (x & 0xf)
            sig, body = f'{ty} {n} (S* p)', f'{{ return {field(off, ty)}; }}'
        elif x & 0xfffff000 == 0xe2800000:
            sig, body = f'void* {n} (S* p)', f'{{ return (char*) p + {rot_imm(x)}; }}'
        elif x & 0xfffff000 == 0xe5801000:
            sig, body = f'void {n} (S* p, int v)', f'{{ {field(x & 0xfff, "int")} = v; }}'
        elif x & 0xfffff000 == 0xe5c01000:
            sig, body = f'void {n} (S* p, unsigned char v)', f'{{ {field(x & 0xfff, "unsigned char")} = v; }}'
    elif s == 8 and w[1] & 0xff000000 == 0xea000000 and branch(w[1], a + 4) in labels:
        fn = callee(branch(w[1], a + 4))
        x = w[0]
        if x & 0xfffff000 == 0xe5900000:
            sig, body = f'void {n} (S* p, int b, int c, int d)', f'{{ {fn} ({field(x & 0xfff, "void*")}, b, c, d); }}'
        elif x & 0xfffff000 == 0xe2800000:
            sig, body = f'void {n} (S* p, int b, int c, int d)', f'{{ {fn} ((char*) p + {rot_imm(x)}, b, c, d); }}'
    if body is None and s in (12, 16, 28):
        x = w
        # movw/movt r3|r0, #global ; (ldr r0,[r3,#o] | str r1,[r3,#o] | strb r1,[r3,#o] | ldrb r0,[r3,#o]) ; bx lr
        def mov32(i):
            lo, hi = x[i], x[i + 1]
            if lo & 0xfff00000 == 0xe3000000 and hi & 0xfff00000 == 0xe3400000 and (lo >> 12) & 0xf == (hi >> 12) & 0xf:
                return (lo >> 12) & 0xf, ((lo >> 4) & 0xf000) | (lo & 0xfff) | ((((hi >> 4) & 0xf000) | (hi & 0xfff)) << 16)
            return None, None
        r, v = mov32(0)
        if r is not None and v in labels:
            g = f'global_{v:x}'
            if g not in decls:
                decls.add(g)
                src.append(f'extern int {g}[] __asm__ ("{labels[v]}");')
            if s == 12 and x[2] == BX and r == 0:
                sig, body = f'void* {n} ()', f'{{ return {g}; }}'
            elif s == 16 and x[3] == BX and r == 3:
                y = x[2]
                if y & 0xfffff000 == 0xe5930000:
                    sig, body = f'int {n} ()', f'{{ return *(int*) ((char*) {g} + {y & 0xfff}); }}'
                elif y & 0xfffff000 == 0xe5d30000:
                    sig, body = f'unsigned char {n} ()', f'{{ return *(unsigned char*) ((char*) {g} + {y & 0xfff}); }}'
                elif y & 0xfffff000 == 0xe5831000:
                    sig, body = f'void {n} (void*, int v)', f'{{ *(int*) ((char*) {g} + {y & 0xfff}) = v; }}'
                elif y & 0xfffff000 == 0xe5c31000:
                    sig, body = f'void {n} (void*, unsigned char v)', f'{{ *(unsigned char*) ((char*) {g} + {y & 0xfff}) = v; }}'
        # movw/movt r3, global ; str r0, [r3, #o] ; bx lr   (static setter)
        if body is None and r == 3 and v in labels and s == 16 and x[3] == BX and x[2] & 0xfffff000 == 0xe5830000:
            sig, body = f'void {n} (int v)', f'{{ *(int*) ((char*) {g} + {x[2] & 0xfff}) = v; }}'
        # movw/movt r3, global ; ldr r0,[r3,#o] ; sub r1,r0,#k ; rsbs r0,r1,#0 ; adc r0,r0,r1 ; bx lr
        if body is None and r == 3 and v in labels and s == 28 and x[6] == BX and x[2] & 0xfffff000 == 0xe5930000 \
                and x[3] & 0xfffff000 == 0xe2401000 and x[4] == 0xe2710000 and x[5] == 0xe0a00001:
            sig, body = f'bool {n} (void*)', f'{{ return *(int*) ((char*) {g} + {x[2] & 0xfff}) == {rot_imm(x[3])}; }}'
        # ldr r3,[r0,#a] ; ldr r0,[r3,#b] ; bx lr
        if body is None and s == 12 and x[2] == BX and x[0] & 0xfffff000 == 0xe5903000 and x[1] & 0xfffff000 == 0xe5930000:
            sig, body = f'int {n} (S* p)', f'{{ return *(int*) ((char*) {field(x[0] & 0xfff, "S*")} + {x[1] & 0xfff}); }}'
    if body is None and s == 12 and w[2] == BX and w[0] & 0xfffff000 == 0xe5903000 and w[1] & 0xfffff000 == 0xe5d30000:
        sig, body = f'unsigned char {n} (S* p)', f'{{ return *(unsigned char*) ((char*) {field(w[0] & 0xfff, "S*")} + {w[1] & 0xfff}); }}'
    # push {r3,lr}; ldr r0,[r0,#o]; bl T; mov r0,#0; pop {r3,pc}
    if body is None and s == 20 and w[0] == 0xe92d4008 and w[1] & 0xfffff000 == 0xe5900000 and \
            w[2] & 0xff000000 == 0xeb000000 and w[3] == 0xe3a00000 and w[4] == 0xe8bd8008 and branch(w[2], a + 8) in labels:
        fn = callee(branch(w[2], a + 8))
        sig, body = f'int {n} (S* p, int b, int c, int d)', f'{{ {fn} ({field(w[1] & 0xfff, "void*")}, b, c, d); return 0; }}'
    # ldr r0,[r0,#o]; push {r3,lr}; ldr r3,[r0]; ldr r3,[r3,#k]; blx r3; pop {r3,pc}
    if body is None and s == 24 and w[0] & 0xfffff000 == 0xe5900000 and w[1] == 0xe92d4008 and w[2] == 0xe5903000 \
            and w[3] & 0xfffff000 == 0xe5933000 and w[4] == 0xe12fff33 and w[5] == 0xe8bd8008 and (w[3] & 0xfff) % 4 == 0 \
            and (w[3] & 0xfff) // 4 < 96:
        sig, body = f'void {n} (S* p, int b, int c)', f'{{ ({field(w[0] & 0xfff, "VTab*")})->m{(w[3] & 0xfff) // 4} (b, c); }}'
    # ldr r0,[r0,#a] ; cmp r0,#0 ; ldrne r0,[r0,#b] ; bx lr
    if body is None and s == 16 and w[0] & 0xfffff000 == 0xe5900000 and w[1] == 0xe3500000 and \
            w[2] & 0xfffff000 == 0x15900000 and w[3] == BX:
        sig, body = f'int {n} (S* p)', f'{{ S* q = {field(w[0] & 0xfff, "S*")}; return q ? *(int*) ((char*) q + {w[2] & 0xfff}) : 0; }}'
    # ldr r0,[r0,#a] ; cmp r0,#0 ; bxeq lr ; b T
    if body is None and s == 16 and w[0] & 0xfffff000 == 0xe5900000 and w[1] == 0xe3500000 and \
            w[2] == 0x012fff1e and w[3] & 0xff000000 == 0xea000000 and branch(w[3], a + 12) in labels:
        fn = callee(branch(w[3], a + 12))
        sig, body = f'void {n} (S* p, int b, int c, int d)', f'{{ void* q = {field(w[0] & 0xfff, "void*")}; if (q) {fn} (q, b, c, d); }}'
    if body:
        src.append(f'{sig} {body}')
        pairs.append((n, a))
src.append('}')
open('src/auto/auto_leaf.cpp', 'w').write('\n'.join(src) + '\n')
open('obj/auto_leaf.pairs', 'w').write(''.join(f'{n}={a:#x}\n' for n, a in pairs))
print(len(pairs), 'functions')
