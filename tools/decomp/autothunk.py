"""Generate this-adjusting thunks (`sub r0, r0, #N; b target`) for multiple-inheritance overriders.

Each thunk only depends on the offset N and the target, so for every ungrafted 8-byte function
of that shape we emit a class whose second base sits at offset N and whose override carries the
target's label as its assembler name; GCC then emits the identical thunk. The C++ names are
placeholders (thunk_<addr>); only the code matters. Writes src/auto/auto_thunks.cpp and
obj/auto_thunks.pairs. Run from decomp/.
"""
import os
import struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from elfinfo import Elf
e = Elf('rbp.orig')
starts = sorted(int(l.split()[0], 16) for l in open('split/functions.txt') if l.startswith('0x'))
size = {a: b - a for a, b in zip(starts, starts[1:])}
grafted = {int(l.split()[0], 16) for l in open('grafts.txt') if l.strip() and l[0] != '#' and l.split()[2] != 'src/auto/auto_thunks.cpp'}   # own earlier output is regenerated
labels = {}
for l in open('split/labels.txt'):
    p = l.split()
    if len(p) == 2:
        labels.setdefault(int(p[0], 16), p[1])

def rot_imm(w):
    imm, rot = w & 0xff, (w >> 8) & 0xf
    return ((imm >> (2 * rot)) | (imm << (32 - 2 * rot))) & 0xffffffff

by_target = {}
for a, s in sorted(size.items()):
    if a in grafted or s not in (8, 12):
        continue
    w = struct.unpack(f'<{s // 4}I', e.read_va(a, s))
    if any(x & 0xfffff000 != 0xe2400000 for x in w[:-1]) or w[-1] & 0xff000000 != 0xea000000:
        continue
    if s == 12 and (w[0] & 0xfff) == (w[1] & 0xfff):
        continue
    n = sum(rot_imm(x) for x in w[:-1])
    off = w[-1] & 0xffffff
    target = a + s + 4 + ((off - 0x1000000) if off & 0x800000 else off) * 4
    if n < 4 or n % 4 or target not in labels:
        continue
    by_target.setdefault(target, {})[n] = a      # one thunk per (target, offset)

src = ['// Generated by scripts/autothunk.py: this-adjusting thunks (sub r0, r0, #N; b target).', '']
pairs = []
for target, offs in sorted(by_target.items()):
    ns = f'thunk_{target:x}'
    ns_offs = sorted(offs)
    bases, prev = [], 0
    decls = []
    # P covers [0, first offset); Qi starts at offset i and runs to the next one
    sizes = [ns_offs[0]] + [b - a for a, b in zip(ns_offs, ns_offs[1:])] + [4]
    names = ['P'] + [f'Q{i}' for i in range(len(ns_offs))]
    for k, (nm, sz) in enumerate(zip(names, sizes)):
        pad = f' char pad[{sz - 4}];' if sz > 4 else ''
        method = 'p' if k == 0 else 'q'
        decls.append(f'struct {nm} {{ virtual void {method}();{pad} }};')
    src.append(f'namespace {ns} {{ ' + ' '.join(decls) + f' struct C : {", ".join(names)} '
               f'{{ void q() __asm__ ("{labels[target]}"); }}; void C::q() {{}} }}')
    for n in ns_offs:
        pairs.append((f'_ZThn{n}_N{len(ns)}{ns}1C1qEv', offs[n]))
open('src/auto/auto_thunks.cpp', 'w').write('\n'.join(src) + '\n')
open('obj/auto_thunks.pairs', 'w').write(''.join(f'{n}={a:#x}\n' for n, a in pairs))
print(len(pairs), 'thunks')
